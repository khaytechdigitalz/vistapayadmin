import React, { useEffect, useRef, useState } from "react";
import { useLocation, useNavigate } from "react-router-dom";
import { toast } from "sonner";
import { verifyLogin2fa } from "@/api/auth";
import { AuthLayout } from "@/components/layout/AuthLayout";
import { useAuth } from "@/context/AuthContext";

const LENGTH = 6;

export const MfaVerification: React.FC = () => {
  const [digits, setDigits] = useState<string[]>(Array(LENGTH).fill(""));
  const [loading, setLoading] = useState(false);
  const [seconds, setSeconds] = useState(45);
  const inputsRef = useRef<(HTMLInputElement | null)[]>([]);

  const { tempToken, handleLoginSuccess } = useAuth();
  const navigate = useNavigate();
  const location = useLocation();

  // Retrieve tempToken from router state or fall back to AuthContext / sessionStorage
  const locationState = location.state as { purpose?: string; tempToken?: string } | null;
  const purpose = locationState?.purpose ?? "2fa";
  const activeTempToken = locationState?.tempToken || tempToken;

  // Countdown timer for code resend
  useEffect(() => {
    if (seconds <= 0) return;
    const t = setTimeout(() => setSeconds((s) => s - 1), 1000);
    return () => clearTimeout(t);
  }, [seconds]);

  // Focus the first input field on initial render
  useEffect(() => {
    inputsRef.current[0]?.focus();
  }, []);

  const executeVerification = async (code: string) => {
    if (!activeTempToken) {
      toast.error("Verification session expired. Please log in again.");
      navigate("/login");
      return;
    }

    setLoading(true);

    try {
      const response = await verifyLogin2fa({
        token: activeTempToken,
        one_time_password: code,
      });

      if (response.status) {
        const authToken = response.data?.token || response.token;

        if (authToken) {
          toast.success(response.message || "2FA verified successfully!");
          await handleLoginSuccess(authToken);

          if (purpose === "reset") {
            navigate("/reset-password");
          } else {
            navigate("/app/dashboard");
          }
        } else {
          toast.error("Authentication token missing in response.");
        }
      } else {
        toast.error(response.message || "Invalid 2FA code.");
      }
    } catch (error: any) {
      const errorMsg =
        error.response?.data?.message || "Verification failed. Please try again.";
      toast.error(errorMsg);
    } finally {
      setLoading(false);
    }
  };

  const handleChange = (index: number, value: string) => {
    // Only accept numeric inputs
    if (value && !/^\d+$/.test(value)) return;

    const next = [...digits];
    // Take last entered character if multiple characters are passed
    next[index] = value.slice(-1);
    setDigits(next);

    // Auto-advance focus to next field
    if (value && index < LENGTH - 1) {
      inputsRef.current[index + 1]?.focus();
    }

    // Auto-submit when all 6 digits are typed in
    const fullCode = next.join("");
    if (fullCode.length === LENGTH) {
      executeVerification(fullCode);
    }
  };

  const handleKeyDown = (index: number, e: React.KeyboardEvent<HTMLInputElement>) => {
    if (e.key === "Backspace" && !digits[index] && index > 0) {
      inputsRef.current[index - 1]?.focus();
    }
  };

  // Enable clipboard paste (e.g. pasting "123456" into any field)
  const handlePaste = (e: React.ClipboardEvent<HTMLInputElement>) => {
    e.preventDefault();
    const pastedData = e.clipboardData.getData("text").trim();

    if (/^\d{6}$/.test(pastedData)) {
      const pastedDigits = pastedData.split("");
      setDigits(pastedDigits);
      inputsRef.current[LENGTH - 1]?.focus();
      executeVerification(pastedData);
    }
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    const code = digits.join("");
    if (code.length < LENGTH) {
      toast.error("Please enter the complete 6-digit code.");
      return;
    }
    executeVerification(code);
  };

  return (
    <AuthLayout>
      <h1 className="text-2xl font-extrabold text-ink-900">Enter Verification Code</h1>
      <p className="mt-2 text-sm text-ink-900/60">
        Enter the 6-digit code generated by your Authenticator app or sent to your device.
      </p>

      <form onSubmit={handleSubmit} className="mt-8">
        <div className="flex justify-between gap-2">
          {digits.map((digit, i) => (
            <input
              key={i}
              ref={(el) => (inputsRef.current[i] = el)}
              value={digit}
              onChange={(e) => handleChange(i, e.target.value)}
              onKeyDown={(e) => handleKeyDown(i, e)}
              onPaste={handlePaste}
              inputMode="numeric"
              maxLength={1}
              disabled={loading}
              className="h-14 w-12 rounded-xl border border-surface-border text-center text-xl font-bold text-ink-900 outline-none transition-colors focus:border-ink-800 disabled:opacity-50"
            />
          ))}
        </div>

        <button
          type="submit"
          disabled={loading || digits.join("").length < LENGTH}
          className="btn-primary mt-8 w-full disabled:opacity-50 disabled:cursor-not-allowed"
        >
          {loading ? "Verifying..." : "Verify Code"}
        </button>
      </form>

      <p className="mt-6 text-center text-sm text-ink-900/60">
        {seconds > 0 ? (
          <>
            Resend code in <span className="font-semibold text-ink-900">{seconds}s</span>
          </>
        ) : (
          <button
            type="button"
            onClick={() => setSeconds(45)}
            className="font-semibold text-ink-900 hover:underline"
          >
            Resend Code
          </button>
        )}
      </p>
    </AuthLayout>
  );
};