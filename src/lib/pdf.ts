import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import type { Invoice } from "@/types";
import { formatNaira } from "./currency";

export function generateInvoicePdf(invoice: Invoice) {
  const doc = new jsPDF();

  // Header band
  doc.setFillColor(14, 59, 57);
  doc.rect(0, 0, 210, 32, "F");
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(18);
  doc.setFont("helvetica", "bold");
  doc.text("VistaPay", 14, 20);
  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text("Invoice", 196, 20, { align: "right" });

  doc.setTextColor(20, 20, 20);
  doc.setFontSize(20);
  doc.setFont("helvetica", "bold");
  doc.text(`#${invoice.number}`, 14, 46);

  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(90, 90, 90);
  doc.text(`Issue date: ${invoice.issueDate}`, 14, 53);
  doc.text(`Due date: ${invoice.dueDate}`, 14, 58);
  doc.text(`Status: ${invoice.status}`, 14, 63);

  doc.setFont("helvetica", "bold");
  doc.setTextColor(20, 20, 20);
  doc.text("Billed to", 140, 46);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(90, 90, 90);
  doc.text(invoice.client, 140, 52);
  if (invoice.clientEmail) doc.text(invoice.clientEmail, 140, 57);
  if (invoice.clientAddress) {
    const lines = doc.splitTextToSize(invoice.clientAddress, 60);
    doc.text(lines, 140, 62);
  }

  const items = invoice.items?.length
    ? invoice.items
    : [{ id: "i1", description: "Services rendered", qty: 1, rate: invoice.amount }];

  autoTable(doc, {
    startY: 78,
    head: [["Item", "Qty", "Rate", "Amount"]],
    body: items.map((it) => [
      it.description,
      String(it.qty),
      formatNaira(it.rate),
      formatNaira(it.qty * it.rate),
    ]),
    headStyles: { fillColor: [14, 59, 57] },
    styles: { fontSize: 10 },
    columnStyles: { 1: { halign: "center" }, 2: { halign: "right" }, 3: { halign: "right" } },
  });

  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const finalY = (doc as any).lastAutoTable?.finalY ?? 100;
  const total = items.reduce((sum, it) => sum + it.qty * it.rate, 0);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(12);
  doc.text("Total", 150, finalY + 12);
  doc.text(formatNaira(total), 196, finalY + 12, { align: "right" });

  if (invoice.notes) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(9);
    doc.setTextColor(120, 120, 120);
    const noteLines = doc.splitTextToSize(invoice.notes, 180);
    doc.text(noteLines, 14, finalY + 28);
  }

  doc.setFontSize(8);
  doc.setTextColor(150, 150, 150);
  doc.text("Generated by VistaPay — vistapay.io", 105, 287, { align: "center" });

  doc.save(`invoice-${invoice.number}.pdf`);
}
